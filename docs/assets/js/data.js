/**
 * Checklist JSON schema upgrade (shared: Apps Script AND the browser copy).
 * _v 1 (no _v) = the checklist ids/options before the FM-MR-58 paper-form update;
 * _v 2 = current. Equivalent PPE options are renamed, PPE options without an
 * equivalent move to that group's "Other" text, retired items (e.g. the old
 * check box "2. เอกสารรับรองที่เกี่ยวข้อง" of งานทั่วไป, now a text field) are kept
 * read-only in _legacy[workType] and shown under "อื่นๆ". Never loses a value;
 * a checklist already at the current version is returned unchanged.
 */
function wpUpgradeChecklist_(raw) {
  var V = WP_DATA.config.checklistVersion;
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return { _v: V };
  if ((Number(raw._v) || 1) >= V) return raw;
  var L = WP_DATA.checklistLegacy, out = {}, legacy = {};
  var has = function (o, k) { return Object.prototype.hasOwnProperty.call(o, k); };
  Object.keys(raw).forEach(function (k) {
    var v = raw[k];
    if (k === '_v' || k === '_legacy') return;
    if (has(L.retired, k)) {
      var r = L.retired[k], text = '';
      if (v === true || v === 1 || v === '1') text = '\u2713 ' + r.label;
      else if (typeof v === 'string' && v.trim() !== '') text = r.label + ': ' + v.trim();
      else if (v && typeof v === 'object' && (v.on || String(v.text || '').trim() !== '')) text = (v.on ? '\u2713 ' : '') + r.label + (String(v.text || '').trim() ? ': ' + String(v.text).trim() : '');
      if (text) (legacy[r.type] = legacy[r.type] || []).push(text);
      return;
    }
    if (has(L.options, k) && v && typeof v === 'object' && Array.isArray(v.sel)) {
      var map = L.options[k], sel = [], extra = [];
      v.sel.forEach(function (o) {
        var n = has(map, o) ? map[o] : o;
        if (n === '') { if (extra.indexOf(o) < 0) extra.push(o); } else if (sel.indexOf(n) < 0) sel.push(n);
      });
      var other = [String(v.other || '').trim()].concat(extra).filter(function (x) { return x !== ''; }).join(', ');
      out[k] = { sel: sel, other: other };
      return;
    }
    out[k] = v;
  });
  if (Object.keys(legacy).length) out._legacy = legacy;
  out._v = V;
  return out;
}
